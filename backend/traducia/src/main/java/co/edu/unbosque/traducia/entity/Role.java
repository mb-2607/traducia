package co.edu.unbosque.traducia.entity;

/**
 * Enumeración que define los roles disponibles en el sistema.
 * 
 * USER: Usuario regular con permisos básicos.
 * ADMIN: Administrador con permisos completos.
 */
public enum Role {
    /** Administrador con acceso a la gestión del sistema. */
    ADMIN,
    /** Usuario estándar del sistema. */
    USER
}
